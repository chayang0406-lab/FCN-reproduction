"""反解作者旧版日志的参数量规律，并说明为什么「D//3 结构式」是错的。

【背景：一次被推翻的推导（务必读完，避免后人重犯）】
我曾给出：
    旧版每层 = w(D x D//3) + b(D) = 130,416；6 层 -> 16,138,194，残差 0
这个式子对 ECN=3/LCN=3 命中，看起来「完全解开了」。**但它是单点巧合。**

拿另外 13 份旧版日志一验就崩：
    L      D//3 式      实际值        一致?
    4      15,616,530   16,038,354    NO
    5      15,877,362   16,088,274    NO
    6      16,138,194   16,138,194    YES  <- 唯一相交点
    7      16,399,026   16,188,114    NO
    8      16,659,858   16,238,034    NO

斜率对比最直接：D//3 式隐含「每层增量 260,832」，而 14 份日志的实际斜率只有 49,920。
差 5 倍多，不可能是同一结构。

【真正的结论】
对全部 14 份旧版日志做线性拟合：
    total = 15,838,674 + 49,920 x (ECN_layers + LCN_layers)
对 14/14 份精确命中（残差全 0），L 覆盖 4–10。
但这**只是经验线性律，不是结构推导**。原因：
  - 旧版源码不在本仓库。git log --all -- src/FCNv2.py 只有 1 次提交；
    旧日志的 checkpoint 路径是 /root/autodl-tmp/model_zoo/DCNv3/DCNv3_torch/，
    说明这些日志来自另一个项目（DCNv3_torch），不是本 FCN 仓库。
  - 只有「参数量」一个观测维度，无法唯一确定层次结构。
  - 49,920 = 2 x 24,960 = 2 x 40 x 624，这个 40 没有对应的自然结构解释，
    强行编一个「每层 40 维」的说法是不诚实的。

所以：旧版只给经验式，并明确标注「结构未确定」。
"""

# 14 份旧版日志的 (ECN, LCN, 实际参数量)，逐份从日志读取。
# 注意：14 个文件里有 13 个不同的 (ECN,LCN) 组合 —— (3,3) 出现了两次
# （FCNv2_Criteo.log 与 FCNv2_Criteo_003_2f44ad9e.log，同配置重复跑）。
OBSERVED = [
    (3, 1, 16038354),
    (3, 2, 16088274),
    (4, 1, 16088274),
    (3, 3, 16138194),
    (5, 1, 16138194),
    (3, 4, 16188114),
    (5, 2, 16188114),
    (3, 5, 16238034),
    (4, 4, 16238034),
    (5, 3, 16238034),
    (4, 5, 16287954),
    (5, 4, 16287954),
    (5, 5, 16337874),
]
N_FILES = 14      # 含 (3,3) 重复那一份
N_UNIQUE = len(OBSERVED)

EMB = 910747 * 16      # = 14,571,952
D = 624

C, S = 15838674, 49920


def main():
    print("=" * 78)
    print("1. 为什么 D//3 结构式是错的")
    print("=" * 78)
    print("  embedding = %d x 16 = %d" % (910747, EMB))
    print("  D = 39 x 16 = %d" % D)
    print("  D//3 式隐含每层 = D*(D//3) + D = %d x %d + %d = %d"
          % (D, D // 3, D, D * (D // 3) + D))
    print("  该式隐含「每加一层，双网络合计 +%d」" % (2 * (D * (D // 3) + D)))
    print("  而 14 份日志拟合出的真实斜率 = %d" % S)
    print("  两者相差 %.1f 倍 -> D//3 不可能是真实结构" % (2 * (D * (D // 3) + D) / S))
    print()
    print("  %-6s %-14s %-14s %s" % ("L", "D//3 式", "实际值", "一致?"))
    for L in range(4, 11):
        mine = EMB + 2 * (L * (D * (D // 3) + D) + 625)
        law = C + S * L
        print("  %-6d %-14d %-14d %s" % (L, mine, law, "YES(巧)" if mine == law else "NO"))

    print()
    print("=" * 78)
    print("2. 经验线性律对 14 份日志的验证")
    print("=" * 78)
    print("  total = %d + %d x (ECN + LCN)" % (C, S))
    print()
    bad = 0
    for e, l, n in OBSERVED:
        pred = C + S * (e + l)
        ok = pred == n
        if not ok:
            bad += 1
        print("    ECN=%d LCN=%d L=%2d  pred=%-10d actual=%-10d %s"
              % (e, l, e + l, pred, n, "OK" if ok else "FAIL"))
    print()
    print("  失败 %d / %d" % (bad, N_UNIQUE))
    if bad == 0:
        print("  ==> 经验线性律对 %d 个不同配置全部精确命中（残差 0）；" % N_UNIQUE)
        print("      对应 %d 份日志文件（(3,3) 有 2 份重复跑）。" % N_FILES)
    print()
    print("=" * 78)
    print("3. 结论")
    print("=" * 78)
    print("  旧版：给经验式（14/14 命中），但【结构未确定】，不可做结构解释。")
    print("  新版：结构推导闭式公式，24/24 命中，可用于独立校验实验配置。")
    print("  旧日志来自 DCNv3_torch 项目，非本仓库；本仓库 git 历史里没有旧版实现。")
    return bad


if __name__ == "__main__":
    raise SystemExit(1 if main() else 0)

